"""Writes tok/graphlib.c and tok/tok_lits.h from fw/graphlib.c: each put_s literal becomes stored tokens, printing goes through tokens. fw/ is only read.

    python tok/gen_fw.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
X210 = os.path.dirname(HERE)
sys.path[:0] = [HERE]
import overlay as O  # noqa: E402
import boot_tok as BT  # noqa: E402
import fragments as F  # noqa: E402
from chipformer.rv import bridge as BR  # noqa: E402

TOK = os.path.expanduser("~/Models/x210/Qwen3.5-4B/tokenizer.json")
if not os.path.exists(TOK):                                        # gq.py build --model: the published model's tokenizer gives the same tables
    TOK = os.path.join(os.environ["TOK_CKPT"], "tokenizer.json")
T = BR.Text(TOK)
O.set_text(T)
src = open(os.path.join(X210, "fw", "graphlib.c")).read()
lits, index = [], {}


def lit_id(s):
    if s not in index:
        index[s] = len(lits)
        lits.append(s)
    return index[s]


def cstr(x):
    return bytes(x, "utf-8").decode("unicode_escape")


def sub_lit(m):
    return f"put_l({lit_id(cstr(m[1]))})"


FN_NAMES = re.search(r"FN\[NFN\] = \{(.*?)\};", src, re.S)[1]
FN_NAMES = re.findall(r'"([^"]*)"', FN_NAMES)
fn0 = None
for n in FN_NAMES:
    i = lit_id(n)
    fn0 = i if fn0 is None else fn0
assert [lit_id(n) for n in FN_NAMES] == list(range(fn0, fn0 + len(FN_NAMES)))

src = src.replace("put_s(FN[f])", f"put_l({fn0} + f)")
src = re.sub(r'put_edge\("([^"]*)"', lambda m: f"put_edge({lit_id(cstr(m[1]))}", src)
# the output section
out_old = src[src.index("static void put_s(const char *s)"): src.index("// ---------------------------------------------------------------- strings")]
out_new = r'''// tok/: printing in Qwen's tokens. An entry: v < 512 printable (a byte or one of four specials); v < 0xFFFF token id v - 512; 0xFFFF: the next two
// u16 are the id, low half first. PEND: a space is waiting and joins the next part, as the tokenizer joins it.
static inline __attribute__((always_inline)) void put_id(u32 id) {
    register u32 r_a0 __asm__("a0") = 511;
    register u32 r_a7 __asm__("a7") = 1;
    __asm__ volatile("ecall\n\taddi x0, %0, 0" : : "r"(id), "r"(r_a0), "r"(r_a7));
}
static u32 PEND;
static void put_run(const u16 *p, const u16 *e) {
    while (p != e) {
        u32 v = *p++;
        if (v < 512) put(v);
        else if (v != 0xFFFFu) put_id(v - 512);
        else { u32 q = p[0] | (u32)p[1] << 16; p += 2; put_id(q); }
    }
}
#include "tok_lits.h"
static const u16 *LTOKOFF, *LTOK, *RTOKOFF, *RTOK;
static void put_l(u32 i) {
    const u16 *o = LIT_O + 3 * i;
    u32 c = o[2];
    if (PEND) put_run(LIT_D + o[1], LIT_D + (c & 0x7FFFu));
    else put_run(LIT_D + o[0], LIT_D + o[1]);
    PEND = c >> 15;
}
static void flush_pend(void) { if (PEND) { PEND = 0; put(' '); } }
static void put_span(const u8 *p, u32 n) { flush_pend(); for (u32 i = 0; i < n; i++) put(p[i]); }
static void put_num(u32 v) {
    char b[11];
    int n = 0;
    flush_pend();
    do { b[n++] = (char)('0' + v % 10); v /= 10; } while (v);
    while (n) put((u8)b[--n]);
}
static void put_lab(u32 h) { put_run(LTOK + LTOKOFF[h], LTOK + LTOKOFF[h + 1]); }
static void put_fmt(u32 h) { put_l(LIT_AT); put_num(h); put_lab(h); }
'''
src = src.replace(out_old, out_new)
# put_edge
old = '''static void put_edge(const char *what, u32 a, u32 r, u32 b) {
    put_s(what); put(' '); put_fmt(a); put_s(" > ");
    u32 d = RELDIR[r];
    put_span(RELNAMES + (d & 0xFFFFu), d >> 16);
    put_s(" > "); put_fmt(b);
}'''
assert old in src
new = '''static void put_edge(u32 what, u32 a, u32 r, u32 b) {
    put_l(what); PEND = 1; put_fmt(a); put_s(" > ");
    put_run(RTOK + RTOKOFF[r], RTOK + RTOKOFF[r + 1]); PEND = 0;
    put_s(" > "); put_fmt(b);
}'''
src = src.replace(old, new)
src = re.sub(r'put_s\("((?:[^"\\]|\\.)*)"\)', sub_lit, src)
assert "put_s(" not in src, re.findall(r".*put_s\(.*", src)[:5]
# the wrapping
m = re.search(r'#ifdef BRIDGE\n        // \\n<tool_response>.*?#else\n        call\(\);\n#endif\n', src, re.S)
assert m
src = src.replace(m[0], '''#ifdef BRIDGE
        // tok/: the real tool turn after </tool_call>, token for token; HALT's echo is the last \\n\\n.
        put_l(LIT_HEAD);
        call();
        PEND = 0;
        put_l(LIT_TAIL);
#else
        call();
#endif
''')
ini = "    N = HDR[1]; R = HDR[2];"
assert ini in src
src = src.replace("    if (N > MAXN) put_l(", """    LTOKOFF = (const u16 *)(BOOTB + HDR[22]);
    LTOK = (const u16 *)(BOOTB + HDR[23]);
    RTOKOFF = (const u16 *)(BOOTB + HDR[24]);
    RTOK = (const u16 *)(BOOTB + HDR[25]);
    if (N > MAXN) put_l(""")
assert "LTOKOFF = " in src
head = "// Generated by tok/gen_fw.py from fw/graphlib.c. Edit the generator, not this file.\n"
open(os.path.join(HERE, "graphlib.c"), "w").write(head + src)

# literals
ID = {}
fixed = {"LIT_AT": None, "LIT_HEAD": None, "LIT_TAIL": None}
ents = lambda ids: BT.encode_entries(ids)
enc = lambda s: T.tok.encode(s, add_special_tokens=False).ids
D, O3 = [], []


def add(no, yes, trail):
    a = len(D)
    D.extend(no)
    b = len(D)
    D.extend(yes)
    c = len(D)
    assert c < 0x8000
    O3.extend((a, b, c | (trail << 15)))


for s in lits:
    trail = s.endswith(" ")
    w = s[:-1] if trail else s
    add(ents(enc(w)), ents(enc(" " + w)), trail)
n = len(lits)
at_i, n = n, n + 1
add(ents(enc("@")), ents(enc(" @")), False)
head_i, n = n, n + 1
add(ents(enc(F.HEAD)), [], False)
tail_ids = enc(F.TAIL)
assert tail_ids[-1] == O.core.NN
tail_i, n = n, n + 1
add(ents(tail_ids[:-1]), [], False)
with open(os.path.join(HERE, "tok_lits.h"), "w") as f:
    f.write("// Generated by tok/gen_fw.py: firmware literals, tokenized once by Qwen's tokenizer. Three offsets per literal: without a pending space, with one, end | trailing-space << 15.\n")
    for i, s in enumerate(lits):
        f.write(f"// {i}: {s!r}\n")
    f.write(f"enum {{ LIT_AT = {at_i}, LIT_HEAD = {head_i}, LIT_TAIL = {tail_i} }};\n")
    f.write("static const u16 LIT_D[] = {" + ", ".join(map(str, D)) + "};\n")
    f.write("static const u16 LIT_O[] = {" + ", ".join(map(str, O3)) + "};\n")
print(n, "literals", len(D), "u16 entries")
